function t(key) {
  let currentLang = 'da';
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      currentLang = window.localStorage.getItem('mtnc_tablet_lang') || 'da';
    }
  } catch (e) {
    currentLang = 'da';
  }
  const dict = Locales[currentLang] || Locales.da;
  return dict[key] || Locales.da[key] || (Locales.en && Locales.en[key]) || key;
}

if (typeof window !== 'undefined') {
  window.Locales = Locales;
  window.t = t;
}
if (typeof module !== 'undefined') {
  module.exports = { Locales, t };
}
